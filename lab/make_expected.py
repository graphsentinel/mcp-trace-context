#!/usr/bin/env python3
"""Writes lab/expected-outcomes.tsv: for every entry of the test plan (lab/plan.py), the outcome the published
measurement (results/measurements.tsv, runs c1 and c2) gave for each call and subject. scripts/summary.py checks a new
test run against this file. Regenerate only when the plan or the published measurement changes:

  python3 lab/make_expected.py

The published runs gave one outcome per (cell-mode, call, subject) in every run, so each line holds one outcome.
Expected 77 (no verdict) and tolerated setup failures are listed with their reason; nothing else may be 77."""
import collections, csv, os, sys

LAB = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(LAB)
sys.path.insert(0, LAB)
import plan  # noqa: E402

OUT = os.path.join(LAB, "expected-outcomes.tsv")
VALUE = ["trace_identity", "parentage", "link", "fwd_tracestate", "fwd_baggage", "first_divergence", "evidence"]
COLS = ["group", "cell", "runs", "call", "subject"] + VALUE + ["note"]

# 77 in the published runs that is a property of the cell, not a lab fault (keyed by cell)
EXPECTED_77 = {f"{Y}-py2-http-auto-split-K3": "A not identifiable: with _meta only and no header the Python server's inbound "
               "span is not tied to the call" for Y in ("Y0", "Y2")}
EXPECTED_77.update({c: "A absent: the Operator's Node.js injection (NODE_OPTIONS=--require) does not instrument the inbound HTTP "
                    "of this ESM server (open-telemetry/opentelemetry-operator#3414); its outbound span starts a new trace"
                    for c in ("Y0-ts1-http-op-same-main", "Y0-ts1-http-op-split-main", "Y4gwoff-ts1-http-op-split-main")})
# cells whose published runs did not measure what the label says: evidence/measured/known-defects.tsv
DEFECTS = os.path.join(ROOT, "evidence", "measured", "known-defects.tsv")
# a setup failure that happened once in the published runs; tolerated in at most one run of the cell
TOLERATED = {"Y0-ts1-http-auto-same-main-notap": "first run on a fresh pod may miss the 15 s export window (O not exported): 77, then COMPLETE"}
TOLERATED.update({f"Y3-{S}-http-obi-same-main": "first run after OBI attaches to a new pod: O not exported, 77, then COMPLETE"
                  for S in ("ts1", "py2")})

HEADER = """# Expected outcome per test-plan entry, call and subject (generated by lab/make_expected.py from results/measurements.tsv).
# cell = run id without the 'lab-' prefix and the -r<N> suffix. runs = planned runs per cell at RUNS=5: the main
#   cell-modes (groups stage-a, py1, gateway, y2b, y4, variant main, tap 1) and y4's K3 run RUNS times; every other entry
#   has a fixed count. Configs: c1, c2 (published 2026-10-08), c3 (Y4), c4 (Operator), c5 (OBI, in a VM
#   without kernel lockdown), 2026-10-12.
# Subjects: A agent-side inbound span on the server, S tools/call span, O the tool's outbound client span,
#   D the downstream API's received context, G the gateway's tools/call span, run = the run as a whole, control = P0/P5.
# Not run (no such cell-mode in the published measurement):
#   stdio x split                    stdio has no HTTP header, so header and _meta cannot differ
#   Y1 (gateway) x stdio             the gateway is placed on Streamable HTTP only
#   Y2b x OTel none                  the experiment hands _meta to OTel's context, so it needs OTel
#   Y1 tracing off x OTel none       not part of the published measurement (Y4 has it)
"""


def tap_of(run_id):
    return "0" if "-notap" in run_id else "L0" if "-tapoff" in run_id else "1"


def main():
    cell_notes = {}
    for d in csv.DictReader(open(DEFECTS), delimiter="\t"):
        cell_notes[d["run_id"].rsplit("-r", 1)[0].split("-", 1)[1]] = (
            "published runs of this cell are a known defect (evidence/measured/known-defects.tsv): " + d["defect"].split(":")[0]
            + "; expected = what they recorded (the tapped cell's outcome)")
    ref = collections.defaultdict(collections.Counter)
    controls = []
    for r in csv.DictReader(open(os.path.join(ROOT, "results", "measurements.tsv")), delimiter="\t"):
        if r["config"] not in ("c1", "c2", "c3", "c4", "c5"):
            continue
        if r["subject"] == "control":
            controls.append(r)
            continue
        cellname = r["run_id"].rsplit("-r", 1)[0].split("-", 1)[1]
        ref[(cellname, r["call"], r["subject"])][tuple(r[c] for c in VALUE)] += 1

    rows = []
    for x in plan.entries(5, with_obi=True):
        if x["kind"] == "P0":
            rows.append({"group": x["group"], "cell": "P0", "runs": 1, "subject": "control", "evidence": "PASS",
                         "note": "driver -> downstream: header verbatim, D trace/parent, D span in exporter"})
            continue
        if x["kind"] == "P5":
            for lang in ("js", "py"):
                rows.append({"group": x["group"], "cell": f"P5:{lang}", "runs": 1, "subject": "control", "evidence": "PASS",
                             "note": "auto-instrumented outbound outside MCP: downstream parent = O, O parent = calibration span"})
            continue
        name = plan.run_id_prefix(x).split("-", 1)[1]
        keys = sorted(k for k in ref if k[0] == name)
        if not keys:
            raise SystemExit(f"no published outcome for plan cell {name}")
        for k in keys:
            vals = [v for v in ref[k] if not (k[2] == "run" and v[-1] == "77")]
            if k[2] == "run":
                continue  # a run-level 77 (setup failure) is handled by TOLERATED below
            if len(vals) != 1:
                raise SystemExit(f"{k}: published runs disagree: {dict(ref[k])}")
            v = dict(zip(VALUE, vals[0]))
            note = EXPECTED_77.get(name, "") if v["evidence"] == "77" else ""
            if v["evidence"] == "77" and not note:
                raise SystemExit(f"{k}: 77 in the published runs without a listed reason")
            note = note or cell_notes.get(name, "")
            rows.append({"group": x["group"], "cell": name, "runs": x["runs"], "call": k[1], "subject": k[2], **v, "note": note})
        if name in TOLERATED:
            rows.append({"group": x["group"], "cell": name, "runs": x["runs"], "subject": "run", "evidence": "77-tolerated",
                         "note": TOLERATED[name]})

    with open(OUT, "w") as f:
        f.write(HEADER)
        f.write("\t".join(COLS) + "\n")
        for r in rows:
            f.write("\t".join(str(r.get(c, "")) for c in COLS) + "\n")
    print(f"{len(rows)} lines -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
